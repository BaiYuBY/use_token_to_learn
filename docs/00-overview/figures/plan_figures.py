"""The roadmap figure and the planner's data / 路线图与计划表数据.

Run via `make figures`, or: PYTHONPATH=scripts python docs/00-overview/figures/plan_figures.py
Writes interactive/plan_data.js (read by interactive/planner.html) and assets/roadmap.png. Instant.
写出 interactive/plan_data.js（供 planner.html 读取）和 assets/roadmap.png。瞬间完成。
"""

import json
import sys
from pathlib import Path

import matplotlib.pyplot as plt
from style import COLORS, apply_style, save

TOPIC = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(TOPIC / "code"))
import study_plan as S  # noqa: E402

DATA_JS = TOPIC / "interactive" / "plan_data.js"
STAGE_COLORS = ["#5c6bc0", "#26a69a", "#e8710a", "#ab47bc"]


def export():
    chapters = {c[0][:2]: {"dir": c[0], "zh": c[1], "en": c[2], "page": S.interactive(c[0]), "stage": S.stage_of(c[0][:2])} for c in S.CHAPTERS}
    data = {"routes": {name: fn() for name, fn in S.ROUTES.items()}, "chapters": chapters,
            "stages": [[s[0], s[1]] for s in S.STAGES], "colors": STAGE_COLORS}
    DATA_JS.parent.mkdir(exist_ok=True)
    DATA_JS.write_text("// Generated by figures/plan_figures.py / 由脚本生成\nwindow.PLAN_DATA = "
                       + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"saved {DATA_JS}")
    return data


def plot(data):
    plan = data["routes"]["standard"]
    fig, ax = plt.subplots(figsize=(14, 3.2))
    stage = 0
    spans = {}
    for i, d in enumerate(plan, 1):
        if d["chapters"]:
            stage = data["chapters"][d["chapters"][0]]["stage"]
            spans.setdefault(d["chapters"][0], [i, i])[1] = i
        color = STAGE_COLORS[stage] if d["kind"] != "review" else "#424242"
        ax.add_patch(plt.Rectangle((i - 0.45, 0), 0.9, 1, color=color, alpha=0.9 if d["kind"] != "setup" else 0.4))
    for cid, (a, b) in spans.items():
        ax.text((a + b) / 2, 1.15, cid, ha="center", va="bottom", fontsize=8)
    for i, d in enumerate(plan, 1):
        if d["kind"] == "review":
            ax.text(i, 0.5, "★", ha="center", va="center", color="white", fontsize=10)
    for k, (zh, en) in enumerate(data["stages"]):
        ax.plot([], [], "s", color=STAGE_COLORS[k], label=f"阶段 {k + 1} / Stage {k + 1}：{zh.split('：')[0]} / {en.split(':')[0]}")
    ax.plot([], [], "s", color="#424242", label="★ 复盘与项目 / review & projects")
    ax.set_xlim(0, len(plan) + 1)
    ax.set_ylim(-0.1, 2.15)
    ax.set_yticks([])
    ax.set_xticks(range(1, len(plan) + 1, 2))
    ax.set_xlabel("标准路线的第几天（每天 60–90 分钟）/ day of the standard route (60–90 minutes a day)")
    ax.set_title(f"标准路线：{len(plan)} 天学完 24 章 / the standard route: 24 chapters in {len(plan)} days", fontsize=10)
    ax.legend(frameon=False, fontsize=8, ncol=3, loc="upper left")
    for side in ("left", "right", "top"):
        ax.spines[side].set_visible(False)
    fig.tight_layout()
    save(fig, __file__, "roadmap.png")


def main():
    apply_style()
    if "--reuse" in sys.argv:
        data = json.loads(DATA_JS.read_text(encoding="utf-8").split("=", 1)[1].rstrip().rstrip(";"))
    else:
        data = export()
    plot(data)


if __name__ == "__main__":
    main()
