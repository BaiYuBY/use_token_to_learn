"""Build one Jupyter notebook per chapter from its code/*.py files / 由每章的 code/*.py 生成 Jupyter notebook.

Run via `make notebooks`, or: python scripts/make_notebooks.py [--check]
The .py files stay the single source of truth (CI runs them); each notebook splits them into one cell per
function or class, adds a setup cell that works locally and in Google Colab, and ends with a cell that runs
the chapter's demo. --check only reports notebooks that are out of date (used by `make check`).
.py 文件始终是唯一的源头（CI 运行它们）；notebook 把它们按函数 / 类拆成单元格，开头加一个在本地和
Colab 都能用的环境单元，最后一个单元运行本章的演示。--check 只检查 notebook 是否过期。
"""

import ast
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPO = "BaiYuBY/use_token_to_learn"
SITE = "https://baiyuby.github.io/use_token_to_learn"
BANNER = re.compile(r"^# -{20,}$")


def colab_url(chapter):
    return f"https://colab.research.google.com/github/{REPO}/blob/main/docs/{chapter}/{chapter}.ipynb"


def md(text):
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n").splitlines(keepends=True)}


def code(text):
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
            "source": text.strip("\n").splitlines(keepends=True)}


def title_of(readme):
    return readme.read_text(encoding="utf-8").splitlines()[0].lstrip("# ").strip()


def interactive_page(chapter_dir):
    pages = sorted((chapter_dir / "interactive").glob("*.html"))
    return pages[0].name if pages else None


def header_cells(chapter_dir):
    chapter = chapter_dir.name
    zh, en = title_of(chapter_dir / "README.md"), title_of(chapter_dir / "README.en.md")
    page = interactive_page(chapter_dir)
    links = [f"[📖 讲解 / Notes]({SITE}/{chapter}/README.html)"]
    if page:
        links.append(f"[🎮 交互演示 / Playground]({SITE}/{chapter}/interactive/{page})")
    links.append(f"[🧑‍💻 GitHub](https://github.com/{REPO}/tree/main/docs/{chapter})")
    intro = f"""# {chapter[:2]} {zh} / {en}

[![Open In Colab](https://colab.research.google.com/assets/colab-badge.svg)]({colab_url(chapter)})

{" · ".join(links)}

这个 notebook 由 `scripts/make_notebooks.py` 根据本章 `code/` 目录下的脚本自动生成，代码与脚本完全一致：每个函数或类是一个单元格，
可以逐个修改、重新运行。最后一个单元格运行本章的演示（带 assert 检查）。

Generated by `scripts/make_notebooks.py` from this chapter's `code/` scripts, with identical code: one cell per function or
class, so you can edit and re-run them one at a time. The last cell runs the chapter's demo (with its assert checks)."""
    setup = f'''# 环境 / setup: find the repository, or clone it (e.g. in Colab); some chapters import code from earlier ones
# 找到仓库，找不到就克隆一份（例如在 Colab 中）；有些章节会导入前面章节的代码
import subprocess
import sys
from pathlib import Path

CHAPTER = "{chapter}"
ROOT = next((p for p in [Path.cwd(), *Path.cwd().parents] if (p / "docs" / CHAPTER).is_dir()), None)
if ROOT is None:
    ROOT = Path.cwd() / "use_token_to_learn"
    if not ROOT.exists():
        subprocess.run(["git", "clone", "--depth", "1", "https://github.com/{REPO}.git", str(ROOT)], check=True)
CODE = ROOT / "docs" / CHAPTER / "code"
sys.path.insert(0, str(CODE))
print("code:", CODE)'''
    return [md(intro), code(setup)]


def leading_start(lines, node):
    """First line of the node including the comments right above it / 包含紧挨在上方的注释."""
    start = (node.decorator_list[0].lineno if getattr(node, "decorator_list", None) else node.lineno) - 1
    while start > 0 and lines[start - 1].startswith("#") and not BANNER.match(lines[start - 1]):
        start -= 1
    return start


def file_cells(path):
    src = path.read_text(encoding="utf-8")
    lines = src.splitlines()
    tree = ast.parse(src)
    body = tree.body
    cells = []
    doc = ast.get_docstring(tree, clean=False)
    if doc:
        body = body[1:]
    cells.append(md(f"## `{path.name}`\n\n```text\n{doc.strip() if doc else path.name}\n```"))
    cells.append(code(f'__file__ = str(CODE / "{path.name}")  # the code below finds its data files from here / 代码据此定位数据文件'))

    # consecutive imports, or consecutive other statements, share a cell / 连续的导入或连续的其他语句合成一个单元格
    chunks, pending, pending_kind = [], [], None

    def flush():
        nonlocal pending, pending_kind
        if pending:
            chunks.append(("code", "\n".join(pending)))
        pending, pending_kind = [], None

    for node in body:
        if (isinstance(node, ast.If) and isinstance(node.test, ast.Compare)
                and getattr(node.test.left, "id", None) == "__name__"):
            continue  # `if __name__ == "__main__"` becomes the final main() cell / 变成最后的 main() 单元格
        start = leading_start(lines, node)
        text = "\n".join(lines[start:node.end_lineno])
        # a section banner just above this node becomes a markdown heading / 上方的分节横幅变成标题
        k = start - 1
        while k >= 0 and not lines[k].strip():
            k -= 1
        if k >= 2 and BANNER.match(lines[k]) and BANNER.match(lines[k - 2]):
            flush()
            chunks.append(("md", "### " + lines[k - 1].lstrip("# ").strip()))
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            flush()
            chunks.append(("code", text))
        else:
            kind = "import" if isinstance(node, (ast.Import, ast.ImportFrom)) else "statement"
            if pending_kind not in (None, kind):
                flush()
            pending.append(text)
            pending_kind = kind
    flush()
    cells += [md(t) if kind == "md" else code(t) for kind, t in chunks]
    has_main = any(isinstance(n, ast.FunctionDef) and n.name == "main" for n in body)
    if has_main:
        cells.append(md(f"### 运行演示 / Run the demo (`{path.name}`)"))
        cells.append(code("main()"))
    return cells



def build(chapter_dir):
    cells = header_cells(chapter_dir)
    for path in sorted((chapter_dir / "code").glob("*.py"), key=order_key):
        cells += file_cells(path)
    cells.append(md("""## 动手试试 / Try it yourself

改一改上面任意一个函数或参数，重新运行它所在的单元格，再运行 `main()` 看结果有什么变化。
assert 失败说明你的改动改变了程序检查的性质，这正是值得思考的地方。

Change any function or parameter above, re-run its cell, then run `main()` again. If an assert fails, your change broke a
property the script checks, which is exactly what is worth thinking about."""))
    nb = {"cells": cells,
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
                       "language_info": {"name": "python"}, "colab": {"provenance": []}},
          "nbformat": 4, "nbformat_minor": 5}
    for i, c in enumerate(cells):
        c["id"] = f"c{i:03d}"
    return json.dumps(nb, ensure_ascii=False, indent=1) + "\n"


def order_key(path):
    """Files that others in the chapter import come first / 被同章其他文件导入的放在前面."""
    others = [p for p in path.parent.glob("*.py") if p != path]
    imported = any(re.search(rf"^from {path.stem} import|^import {path.stem}\b", p.read_text(), re.M) for p in others)
    return (0 if imported else 1, path.name)


def main():
    check = "--check" in sys.argv
    stale = []
    for chapter_dir in sorted(ROOT.glob("docs/[0-9][0-9]-*")):
        if not (chapter_dir / "code").is_dir():
            continue
        out = chapter_dir / f"{chapter_dir.name}.ipynb"
        text = build(chapter_dir)
        if out.exists() and out.read_text(encoding="utf-8") == text:
            continue
        if check:
            stale.append(out)
        else:
            out.write_text(text, encoding="utf-8")
            print(f"wrote {out.relative_to(ROOT)}")
    if stale:
        print("out of date, run `make notebooks`:\n  " + "\n  ".join(str(p.relative_to(ROOT)) for p in stale))
        sys.exit(1)


if __name__ == "__main__":
    main()
